-- #1482 - bring every database's VendorEnquiry to the shape in prisma/schema.prisma, keeping rows.
--
-- WHY THIS EXISTS. `20261109225000_vendor_enquiries` was edited in place on 2026-11-10 (enums for
-- source/status, replies moved to VendorEnquiryReply) after `prisma migrate status` showed it
-- unapplied on dev. But its ORIGINAL text had already been applied by hand on 2026-11-09 22:48 UTC to
-- three databases - AFC staging, AFC production and Merqify production - and `prisma migrate deploy`
-- never re-checks the checksum of an applied migration, so those three kept the old shape (TEXT
-- source/status, replyBody/repliedAt/repliedBy columns, no VendorEnquiryReply). Dev and Merqify
-- staging applied the edited text and are already correct.
--
-- WHAT IT DOES. Everything is guarded, so one file is correct on both shapes:
--   - old shape (a "replyBody" column exists): create the two enums if missing, convert source and
--     status to them, create VendorEnquiryReply (same DDL as the edited migration), copy each
--     recorded reply into it, then remove the three reply columns;
--   - new shape: every guard is false and nothing changes.
-- A source/status value outside the enums makes the cast fail and the whole migration roll back,
-- which is the intended loud failure rather than a silent rewrite (all three databases held 0 rows
-- when checked on 2026-11-10).
--
-- HAND-AUTHORED, not generated by `prisma migrate dev --create-only`: that command refuses on the
-- dev database ("The migration `20260820200500_p8_image_needs_review` was modified after it was
-- applied") and offers only `migrate reset`, which would delete every row - the open `#895`. Prisma
-- cannot generate a conditional migration in any case: against prisma/schema.prisma this file is a
-- no-op, which is what `prisma migrate diff` reports. Spec:
-- specs/2026-11-10-pr1481-enquiries-team-access-retro/ (R30a).

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'VendorEnquiry'
      AND column_name = 'replyBody'
  ) THEN
    -- CreateEnum (only where missing)
    IF NOT EXISTS (
      SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
      WHERE t.typname = 'EnquirySource' AND n.nspname = current_schema()
    ) THEN
      CREATE TYPE "EnquirySource" AS ENUM ('CONTACT_FORM', 'INBOUND_EMAIL');
    END IF;

    IF NOT EXISTS (
      SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
      WHERE t.typname = 'EnquiryStatus' AND n.nspname = current_schema()
    ) THEN
      CREATE TYPE "EnquiryStatus" AS ENUM ('OPEN', 'REPLIED', 'RESOLVED');
    END IF;

    -- AlterTable: TEXT -> enum
    ALTER TABLE "VendorEnquiry"
      ALTER COLUMN "source" TYPE "EnquirySource" USING "source"::"EnquirySource";
    ALTER TABLE "VendorEnquiry" ALTER COLUMN "status" DROP DEFAULT;
    ALTER TABLE "VendorEnquiry"
      ALTER COLUMN "status" TYPE "EnquiryStatus" USING "status"::"EnquiryStatus";
    ALTER TABLE "VendorEnquiry" ALTER COLUMN "status" SET DEFAULT 'OPEN';

    -- CreateTable (identical to 20261109225000_vendor_enquiries as edited)
    CREATE TABLE IF NOT EXISTS "VendorEnquiryReply" (
        "id" TEXT NOT NULL,
        "enquiryId" TEXT NOT NULL,
        "body" TEXT NOT NULL,
        "sentBy" TEXT NOT NULL,
        "sentAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

        CONSTRAINT "VendorEnquiryReply_pkey" PRIMARY KEY ("id")
    );

    -- CreateIndex
    CREATE INDEX IF NOT EXISTS "VendorEnquiryReply_enquiryId_sentAt_idx"
      ON "VendorEnquiryReply"("enquiryId", "sentAt");

    -- AddForeignKey
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace
      WHERE c.conname = 'VendorEnquiryReply_enquiryId_fkey' AND n.nspname = current_schema()
    ) THEN
      ALTER TABLE "VendorEnquiryReply" ADD CONSTRAINT "VendorEnquiryReply_enquiryId_fkey"
        FOREIGN KEY ("enquiryId") REFERENCES "VendorEnquiry"("id") ON DELETE CASCADE ON UPDATE CASCADE;
    END IF;

    -- Keep every recorded reply before its columns go
    INSERT INTO "VendorEnquiryReply" ("id", "enquiryId", "body", "sentBy", "sentAt")
    SELECT gen_random_uuid()::text, "id", "replyBody", COALESCE("repliedBy", 'unknown'),
           COALESCE("repliedAt", "updatedAt")
    FROM "VendorEnquiry"
    WHERE "replyBody" IS NOT NULL;

    -- AlterTable: the reply columns now live in VendorEnquiryReply
    ALTER TABLE "VendorEnquiry" DROP COLUMN "replyBody";
    ALTER TABLE "VendorEnquiry" DROP COLUMN "repliedAt";
    ALTER TABLE "VendorEnquiry" DROP COLUMN "repliedBy";
  END IF;
END $$;
