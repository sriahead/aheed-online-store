import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * #1211 (R8) — "can a shopper buy this?" has ONE answer: `purchasableQuantity()` in
 * lib/cart-rules.ts. Before #1211 it was derived in four places, three of them as an inline
 * `(inventory?.quantity ?? 0) > 0` that ignored the stock mode and the restriction entirely. Those
 * shapes are the ones that come back when someone writes a new mapper by copying an old one, so
 * this fails on either reappearing anywhere in the app.
 *
 * The one legitimate `quantity: { gt: 0 }` is `buildFilterWhere`'s in-stock predicate, which is
 * the same rule expressed as a database filter (TRACKED with stock, OR'd with UNTRACKED).
 */

const ROOT = join(__dirname, "..");
const SCANNED = ["lib", "app", "features", "components"];
const INLINE_DERIVATION = /inventory\??\.quantity\s*\?\?\s*0\)\s*>\s*0/;
const QUANTITY_PREDICATE = /quantity:\s*\{\s*gt:\s*0\s*\}/;
/**
 * Generated by `kms:build-index`: it embeds the specs and architecture docs as TEXT, and those
 * quote both patterns on purpose. Documentation, not code.
 */
const GENERATED_DOCS = join("app", "(admin)", "staff", "runbook", "docs.ts");

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourceFiles(path);
    if (relative(ROOT, path) === GENERATED_DOCS) return [];
    return /\.(ts|tsx)$/.test(name) && !/\.test\./.test(name) ? [path] : [];
  });
}

/** The body of `buildFilterWhere`, the one place the predicate is allowed. */
function buildFilterWhereBody(source: string): string {
  const start = source.indexOf("export function buildFilterWhere(");
  if (start === -1) return "";
  const end = source.indexOf("\n}\n", start);
  return source.slice(start, end);
}

describe("purchasability has a single source (R8)", () => {
  const files = SCANNED.flatMap((dir) => sourceFiles(join(ROOT, dir)));

  it("scans a real tree", () => {
    expect(files.length).toBeGreaterThan(100);
  });

  it("no file re-derives availability as (inventory?.quantity ?? 0) > 0", () => {
    const offenders = files
      .filter((file) => INLINE_DERIVATION.test(readFileSync(file, "utf8")))
      .map((file) => relative(ROOT, file));
    expect(offenders).toEqual([]);
  });

  it("quantity: { gt: 0 } appears only inside buildFilterWhere", () => {
    const offenders = files.flatMap((file) => {
      const source = readFileSync(file, "utf8");
      if (!QUANTITY_PREDICATE.test(source)) return [];
      const outside = source.replace(buildFilterWhereBody(source), "");
      return QUANTITY_PREDICATE.test(outside) ? [relative(ROOT, file)] : [];
    });
    expect(offenders).toEqual([]);
  });
});
